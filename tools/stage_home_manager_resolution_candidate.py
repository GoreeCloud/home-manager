#!/usr/bin/env python3
"""Generate a throwaway, non-release dependency resolution overlay.

The imported requirements and package constraints are READ ONLY. Exactly the
two source-reviewed Linux ABI3 audio candidates are substituted in fresh,
private runner files. The original PyTurboJPEG version remains unchanged and
requires a separately verified locally built wheel. Nothing is installed.
"""

from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import sys

OVERRIDES = {
    "pymicro-vad": ("1.0.1", "2.1.0"),
    "pyspeex-noise": ("1.0.2", "2.0.1"),
}
CONSTRAINT_DIRECTIVE = "-c homeassistant/package_constraints.txt"
JPEG_PIN = "PyTurboJPEG==1.8.3"
EXPECTED_PYTHON = "3.14.10"


def replace_exact_pins(text: str) -> str:
    """Replace only two exact declarative requirement lines, no code evaluation."""
    lines = text.splitlines(keepends=True)
    for package, (old, new) in OVERRIDES.items():
        expected = f"{package}=={old}"
        occurrences = [i for i, line in enumerate(lines) if line.strip() == expected]
        if len(occurrences) != 1:
            raise ValueError("source requirements changed or duplicate pin: " + package)
        index = occurrences[0]
        lines[index] = lines[index].replace(expected, f"{package}=={new}", 1)
    if sum(line.strip() == JPEG_PIN for line in lines) != 1:
        raise ValueError("original PyTurboJPEG pin unexpectedly changed")
    return "".join(lines)


def stage_overlay(root: Path, destination: Path) -> dict[str, object]:
    """Preserve source bytes, write two isolated candidate files and SHA ledger."""
    req_path = root / "requirements.txt"
    con_path = root / "homeassistant/package_constraints.txt"
    for file in (req_path, con_path):
        if file.is_symlink() or not file.is_file() or file.stat().st_size > 150_000:
            raise ValueError("requirements file is missing or unsafe")
    if destination.exists() or destination.parent.is_symlink() or not destination.parent.is_dir():
        raise ValueError("candidate destination must be a new private directory")

    req_bytes = req_path.read_bytes()
    con_bytes = con_path.read_bytes()
    req = req_bytes.decode("utf-8")
    con = con_bytes.decode("utf-8")
    if req.count(CONSTRAINT_DIRECTIVE) != 1:
        raise ValueError("unexpected inherited constraints directive")
    if not req.startswith("# Automatically generated by gen_requirements_all.py"):
        raise ValueError("unrecognized inherited requirements source")

    new_con = replace_exact_pins(con)
    new_req = replace_exact_pins(req)
    new_req = new_req.replace(CONSTRAINT_DIRECTIVE, "-c " + str(destination / "constraints.txt"), 1)
    if "-c homeassistant/package_constraints.txt" in new_req:
        raise ValueError("old constraints directive remains in candidate")

    manifest: dict[str, object] = {
        "scope": "disposable Linux Python 3.14.10 metadata-only candidate resolution",
        "source_requirements_sha256": sha256(req_bytes).hexdigest(),
        "source_constraints_sha256": sha256(con_bytes).hexdigest(),
        "changes": {name: {"imported": old, "candidate": new} for name, (old, new) in OVERRIDES.items()},
        "jpeg_source_pin": JPEG_PIN,
        "original_files_modified": False,
    }
    destination.mkdir(mode=0o700, exist_ok=False)
    (destination / "constraints.txt").write_text(new_con, encoding="utf-8")
    (destination / "requirements.in").write_text(new_req, encoding="utf-8")
    (destination / "source-ledger.json").write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args(argv)
    if sys.version_info[:3] != (3, 14, 10) or sys.platform != "linux":
        print("OVERLAY FAIL: expected supported Linux Python 3.14.10", file=sys.stderr)
        return 2
    try:
        manifest = stage_overlay(args.root, args.output_dir)
    except (ValueError, OSError, UnicodeError) as exc:
        print("OVERLAY FAIL: " + type(exc).__name__, file=sys.stderr)
        return 2
    print("OVERLAY PASS: 2 audio candidate substitutions; PyTurboJPEG original 1.8.3 pin unchanged")
    print("Original source SHA-256: " + str(manifest["source_requirements_sha256"]))
    print("Scope: candidate metadata solving only; no source changes, package installs, runtime tests or release")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
