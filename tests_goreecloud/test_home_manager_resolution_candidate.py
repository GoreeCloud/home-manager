"""Dependency-free tests for the disposable Core resolver candidate overlay."""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools/stage_home_manager_resolution_candidate.py"
SPEC = importlib.util.spec_from_file_location("home_manager_candidate_overlay", SOURCE)
assert SPEC is not None and SPEC.loader is not None
mod = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(mod)

REQUIREMENTS = """# Automatically generated by gen_requirements_all.py, do not edit

-c homeassistant/package_constraints.txt

pymicro-vad==1.0.1
pyspeex-noise==1.0.2
PyTurboJPEG==1.8.3
"""
CONSTRAINTS = """# Automatically generated by gen_requirements_all.py, do not edit
pymicro-vad==1.0.1
pyspeex-noise==1.0.2
PyTurboJPEG==1.8.3
"""


class CoreResolutionCandidateTests(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name) / "source"
        self.root.mkdir()
        (self.root / "homeassistant").mkdir()
        self.req = self.root / "requirements.txt"
        self.con = self.root / "homeassistant/package_constraints.txt"
        self.req.write_text(REQUIREMENTS, encoding="utf-8")
        self.con.write_text(CONSTRAINTS, encoding="utf-8")
        self.out = Path(tmp.name) / "candidate"

    def test_candidate_has_exact_two_audio_changes_without_touching_source(self) -> None:
        original_req = self.req.read_bytes()
        original_con = self.con.read_bytes()
        report = mod.stage_overlay(self.root, self.out)
        self.assertEqual(self.req.read_bytes(), original_req)
        self.assertEqual(self.con.read_bytes(), original_con)
        self.assertEqual(report["original_files_modified"], False)
        produced = (self.out / "requirements.in").read_text(encoding="utf-8")
        constraints = (self.out / "constraints.txt").read_text(encoding="utf-8")
        for text in (produced, constraints):
            self.assertIn("pymicro-vad==2.1.0", text)
            self.assertIn("pyspeex-noise==2.0.1", text)
            self.assertIn("PyTurboJPEG==1.8.3", text)
            self.assertNotIn("pymicro-vad==1.0.1", text)
            self.assertNotIn("pyspeex-noise==1.0.2", text)
        self.assertIn("-c " + str(self.out / "constraints.txt"), produced)
        self.assertEqual(json.loads((self.out / "source-ledger.json").read_text())["jpeg_source_pin"], mod.JPEG_PIN)
        self.assertEqual({p.name for p in self.out.iterdir()}, {
            "requirements.in", "constraints.txt", "source-ledger.json"
        })

    def test_both_source_files_require_every_expected_old_pin(self) -> None:
        for file in (self.req, self.con):
            with self.subTest(file=file.name):
                file.write_text(file.read_text().replace("pyspeex-noise==1.0.2", ""), encoding="utf-8")
                with self.assertRaises(ValueError):
                    mod.stage_overlay(self.root, self.out)
                self.assertFalse(self.out.exists())
                file.write_text(REQUIREMENTS if file is self.req else CONSTRAINTS, encoding="utf-8")

    def test_malformed_extra_old_pin_is_rejected(self) -> None:
        self.con.write_text(CONSTRAINTS + "\npymicro-vad==1.0.1\n")
        with self.assertRaises(ValueError):
            mod.stage_overlay(self.root, self.out)

    def test_changed_legacy_jpeg_pin_rejected(self) -> None:
        self.req.write_text(REQUIREMENTS.replace("PyTurboJPEG==1.8.3", "PyTurboJPEG==2.0.0"))
        with self.assertRaisesRegex(ValueError, "PyTurboJPEG"):
            mod.stage_overlay(self.root, self.out)

    def test_missing_constraint_directive_rejected(self) -> None:
        self.req.write_text(REQUIREMENTS.replace("-c homeassistant/package_constraints.txt", ""))
        with self.assertRaisesRegex(ValueError, "constraints directive"):
            mod.stage_overlay(self.root, self.out)

    def test_output_directory_cannot_be_overwritten(self) -> None:
        self.out.mkdir()
        (self.out / "important.txt").write_text("preserve")
        with self.assertRaisesRegex(ValueError, "new private directory"):
            mod.stage_overlay(self.root, self.out)
        self.assertEqual((self.out / "important.txt").read_text(), "preserve")

    def test_symlink_requirements_rejected(self) -> None:
        original = self.req.read_bytes()
        self.req.unlink()
        alternative = self.root / "outside.txt"
        alternative.write_bytes(original)
        self.req.symlink_to(alternative)
        with self.assertRaises(ValueError):
            mod.stage_overlay(self.root, self.out)

    def test_review_branch_only_workflow_and_hash_pin(self) -> None:
        workflow = (ROOT / ".github/workflows/home-manager-import-checks.yml").read_text(encoding="utf-8")
        self.assertIn("core-resolution-candidate-uv:", workflow)
        self.assertIn("github.head_ref == 'ci/core-resolution-candidate-uv-20261108'", workflow)
        self.assertIn("uv==0.13.6", workflow)
        self.assertIn("22759b8895e1103578de6fb4cd27e94b4399d021023378d29f01333717751fba", workflow)
        self.assertIn("--no-build", workflow)
        self.assertIn("--only-binary :all:", workflow)
        self.assertIn("stage_home_manager_resolution_candidate.py", workflow)


if __name__ == "__main__":
    unittest.main()
